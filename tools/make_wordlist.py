import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "eff_large_wordlist.txt"
OUT = ROOT / "Sources" / "Engine" / "wordlist.h"
SHA256 = "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"

raw = SRC.read_bytes()
if hashlib.sha256(raw).hexdigest() != SHA256:
    raise SystemExit(f"{SRC}: unexpected SHA-256, not the EFF list")

words = [line.split("\t")[1] for line in raw.decode("ascii").splitlines() if line.strip()]
assert len(words) == 7776 and len(set(words)) == 7776, len(words)
assert all(w and all(c.isascii() and (c.islower() or c == "-") for c in w) for w in words)

lines = [
    "/**",
    "  Wyrmhold -- the passphrase word list.",
    "  Copyright (C) 2026 Gabriel Castiglia. Licensed under the GNU GPL, version 2 only.",
    "  Date: November 10, 2026",
    "  SPDX-License-Identifier: GPL-2.0-only",
    "",
    "  Generated by tools/make_wordlist.py from assets/eff_large_wordlist.txt; do not edit.",
    "  The EFF large word list, by the Electronic Frontier Foundation, CC BY 3.0 US",
    "  (https://www.eff.org/dice): 7776 words, so each word drawn adds log2(7776) = 12.9 bits.",
    "**/",
    "",
    "#ifndef WORDLIST_H",
    "#define WORDLIST_H",
    "",
    "#define WORD_COUNT 7776",
    "",
    "static const char* const WORDS[WORD_COUNT] = {",
]
row = []
for w in words:
    row.append(f'"{w}",')
    if sum(len(x) + 1 for x in row) > 88:
        lines.append("\t" + " ".join(row))
        row = []
if row:
    lines.append("\t" + " ".join(row))
lines += ["};", "", "#endif", ""]
OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
print(f"wrote {OUT} ({len(words)} words)")
